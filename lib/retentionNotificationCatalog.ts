export type RetentionScenarioSeed = {
  key: string;
  name: string;
  description: string;
  dayPart: 'morning' | 'day' | 'evening' | 'reactivation';
  timeWindowStart: string;
  timeWindowEnd: string;
  priority: number;
  maxPerDay: number;
  cooldownHours: number;
  segment: string;
  deepLinkSection: string;
  imageTags: string[];
  templates: Array<{
    title: string;
    body: string;
    buttonText: string;
    tags: string[];
    weight?: number;
  }>;
};

function template(title: string, body: string, buttonText: string, tags: string[]) {
  return { title, body, buttonText, tags, weight: 100 };
}

function eight(
  title: string,
  bodies: string[],
  buttonText: string,
  tags: string[]
): RetentionScenarioSeed['templates'] {
  return bodies.slice(0, 8).map((body, index) => template(index === 0 ? title : `${title} · ${index + 1}`, body, buttonText, tags));
}

