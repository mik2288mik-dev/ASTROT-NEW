export type RetentionScenarioSeed = {
  key: string;
  name: string;
  description: string;
  dayPart: 'morning' | 'day' | 'evening' | 'reactivation';
  timeWindowStart: string;
  timeWindowEnd: string;
  priority: number;
  maxPerDay: number;
  cooldownHours: number;
  segment: string;
  deepLinkSection: string;
  imageTags: string[];
  templates: Array<{
    title: string;
    body: string;
    buttonText: string;
    tags: string[];
    weight?: number;
  }>;
};

function template(title: string, body: string, buttonText: string, tags: string[]) {
  return { title, body, buttonText, tags, weight: 100 };
}

function eight(
  title: string,
  bodies: string[],
  buttonText: string,
  tags: string[]
): RetentionScenarioSeed['templates'] {
  // Все варианты одного сценария — с ОДНИМ чистым заголовком. Раньше к нему
  // прибавлялся номер шаблона ("· 4"), и он лез в пуш.
  return bodies.slice(0, 8).map((body) => template(title, body, buttonText, tags));
}

