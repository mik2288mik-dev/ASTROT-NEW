function createScheduledSeeds(
  label: string,
  slot: NotificationSlot,
  targetSegment: AdminNotificationTargetSegment | null,
  texts: string[],
  sendTime: string,
  notes: string
): ScheduledNotificationSeed[] {
  const slotConfig = getNotificationSlotConfig(slot);
  return texts.map((text, index) => ({
    name: `${label} · ${String(index + 1).padStart(2, '0')}`,
    slot,
    targetSegment,
    text,
    buttonText: slotConfig.defaultButtonText,
    deepLink: getNotificationSlotDefaultDeepLink(slot),
    visualMode: 'none',
    isActive: false,
    notes,
    schedules: [
      {
        sendTime,
        timezone: DEFAULT_TIMEZONE,
        repeatMode: slotConfig.defaultRepeatMode,
        isActive: false,
      },
    ],
  }));
}

