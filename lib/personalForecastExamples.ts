import type { PersonalForecastPeriod } from './personalForecastContract';

type Tone = 'bright' | 'steady' | 'challenging';
type Output = { title: string; forecast: string; closing: string };

export type PersonalForecastReferenceExample = {
  id: string;
  period: PersonalForecastPeriod;
  tone: Tone;
  input: {
    reference_scope: 'voice_and_structure_only';
    reader: { language: 'ru'; grammatical_gender: 'unspecified' };
    selected_period: { period: PersonalForecastPeriod };
    astrologer_brief: {
      tone: 'favorable' | 'mixed' | 'demanding';
      observations: string[];
    };
  };
  output: Output;
};

function example(
  id: string,
  period: PersonalForecastPeriod,
  tone: Tone,
  output: Output,
  observations: string[],
): PersonalForecastReferenceExample {
  return {
    id, period, tone, output,
    input: {
      reference_scope: 'voice_and_structure_only',
      reader: { language: 'ru', grammatical_gender: 'unspecified' },
      selected_period: { period },
      astrologer_brief: {
        tone: tone === 'bright' ? 'favorable' : tone === 'challenging' ? 'demanding' : 'mixed',
        observations,
      },
    },
  };
}

