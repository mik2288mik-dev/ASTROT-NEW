/** World firsts of the birth year, rotated by day; `offset` picks a second, different one. */
export function worldTwinOfDay(birthDate: string, dayIndex: number, offset = 0): WorldTwin | null {
  const year = Number(birthDate.slice(0, 4));
  const list = TWINS[year];
  if (!list?.length || offset >= list.length) return null;
  return list[(dayIndex + offset) % list.length];
}
