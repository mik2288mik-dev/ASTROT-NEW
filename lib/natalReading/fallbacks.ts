/**
 * Static, chart-aware fallbacks for the natal-reading screen.
 *
 * Used when the OpenAI generation step fails, when the API key is missing,
 * or when the prompt response cannot be parsed. The idea: never show an
 * empty / "GENERATION_FAILED" screen — at minimum the user sees a personalised
 * portrait built from their actual chart data.
 */

import type { SerializedChartForPrompt } from './chartSerializer';
import type {
  NatalReadingAspects,
  NatalReadingDeepDive,
  NatalReadingDeepDiveKey,
  NatalReadingPortrait,
  NatalReadingToday,
  NatalReadingWeek,
} from './types';

const ELEMENT: Record<string, 'fire' | 'earth' | 'air' | 'water'> = {
  Овен: 'fire',
  Лев: 'fire',
  Стрелец: 'fire',
  Телец: 'earth',
  Дева: 'earth',
  Козерог: 'earth',
  Близнецы: 'air',
  Весы: 'air',
  Водолей: 'air',
  Рак: 'water',
  Скорпион: 'water',
  Рыбы: 'water',
};

