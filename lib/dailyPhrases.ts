function hash(value: string): number {
  let result = 0;
  for (let index = 0; index < value.length; index += 1) result = (result * 31 + value.charCodeAt(index)) >>> 0;
  return result;
}

/** One phrase per person per day; different people get different lines on the same day. */
export function dailyPhrase(userId: string, day: number): string {
  return PHRASES[(day + hash(userId)) % PHRASES.length];
}
