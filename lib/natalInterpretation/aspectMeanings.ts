export function aspectMeaningRu(fact: NatalInterpretationEvidence): { text: string; topics: NatalMeaningTopic[] } | null {
  if (!fact.fromKey || !fact.toKey || !fact.aspectType) return null;
  const pair = PAIRS[[fact.fromKey, fact.toKey].sort().join(':')];
  if (!pair) return null;
  const field: Record<NatalAspectType, 'joined' | 'support' | 'tension'> = {
    conjunction: 'joined', sextile: 'support', trine: 'support', square: 'tension', opposition: 'tension',
  };
  const text = pair[field[fact.aspectType]];
  return { text, topics: pair.topics };
}
