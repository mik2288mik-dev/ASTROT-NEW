export function moneyHouseMeaning(house: number, sign: string): string | null {
  if (house !== 2 && house !== 8) return null;
  const index = Object.keys(SIGN_STYLE_RU).indexOf(sign);
  if (index < 0) return null;
  const text = MONEY_SIGN_COPY_RU[index];
  return house === 8
    ? text.replace(/^В денежных вопросах/u, 'Когда решаешь, как распорядиться общими деньгами,')
      .replace(/^В денежных решениях/u, 'Когда решаешь, как распорядиться общими деньгами,')
      .replace(/^В покупках/u, 'В совместных покупках')
      .replace(/^Перед покупкой/u, 'Перед совместной покупкой')
      .replace(/^Важный денежный вопрос/u, 'Важный вопрос об общих деньгах')
    : text;
}

