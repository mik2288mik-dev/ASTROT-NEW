function element(sign: string) {
  return ELEMENT[sign] || 'air';
}

function signTrait(sign: string): string {
  return SIGN_TRAIT[sign] || 'сначала оценивает ситуацию, потом принимает решение';
}

function moonTrait(sign: string): string {
  return MOON_TRAIT[sign] || 'реакция зависит от того, насколько понятна и безопасна ситуация';
}

export function buildPortraitFallback(chart: SerializedChartForPrompt): NatalReadingPortrait {
  const sun = chart.signature.sun;
  const moon = chart.signature.moon;
  const rising = chart.signature.rising;
  const sunText = signTrait(sun);
  const moonText = moonTrait(moon);
  const risingText = signTrait(rising);

  const archetypes: NatalReadingPortrait['archetypes'] = [
    {
      title: 'Как принимаешь решения',
      subtitle: `Солнце в ${sun}: ${sunText}`,
    },
    {
      title: 'Как реагируешь',
      subtitle: `Луна в ${moon}: ${moonText}`,
    },
    {
      title: 'Первое впечатление',
      subtitle: `Асцендент в ${rising}: ${risingText}`,
    },
    {
      title: 'Что получается лучше',
      subtitle: 'Собрать факты и выбрать понятный следующий шаг',
    },
    {
      title: 'Где начинаются проблемы',
      subtitle: 'Когда приходится долго действовать без ясного ответа',
    },
  ];

  const portrait =
    `При первой встрече тебя чаще воспринимают как человека, который ${risingText}. ` +
    `В решениях сильнее заметно Солнце в ${sun}: ты ${sunText}. ` +
    `Луна в ${moon} описывает реакцию на напряжение: ${moonText}. ` +
    'Из-за этого внешний ответ и то, что происходит внутри, не всегда совпадают. ' +
    'Ты можешь выглядеть спокойнее или жёстче, чем ощущаешь себя в этот момент.';

  const insight =
    'Ты можешь считать свою сдержанность обычной осторожностью, а другие люди — холодностью или недоверием. ' +
    'Проблема чаще не в самой дистанции, а в том, что её причина остаётся непонятной.';

  return {
    archetypes,
    portrait,
    insight,
    energyA: {
      title: `Решения: ${sun}`,
      body: `Солнце в ${sun} связано с тем, как ты выбираешь направление и берёшь ответственность. В твоём случае это чаще выглядит так: ${sunText}.`,
    },
    energyB: {
      title: `Реакции: ${moon}`,
      body: `Луна в ${moon} связана с быстрой внутренней реакцией. В напряжённой ситуации ${moonText}.`,
    },
    synthesis:
      'Решение получается точнее, когда ты отдельно проверяешь две вещи: чего хочешь добиться и что сейчас вызывает реакцию. ' +
      'Если смешать их, легко принять эмоциональный ответ за окончательное решение.',
  };
}

export function buildAspectsFallback(chart: SerializedChartForPrompt): NatalReadingAspects {
  const sun = chart.signature.sun;
  const moon = chart.signature.moon;
  const rising = chart.signature.rising;
  const sameElement = element(sun) === element(moon);

  return {
    aspects: [
      {
        pl: `Солнце · ${sun}`,
        badge: 'Положение',
        color: '#c9a55a',
        text: `Солнце в ${sun} связано с решениями и способом добиваться результата. Ты ${signTrait(sun)}.`,
      },
      {
        pl: `Луна · ${moon}`,
        badge: 'Положение',
        color: '#c9a55a',
        text: `Луна в ${moon} описывает реакцию на напряжение и близость. ${moonTrait(moon)[0].toUpperCase() + moonTrait(moon).slice(1)}.`,
      },
      {
        pl: `Асцендент · ${rising}`,
        badge: 'Положение',
        color: '#9a9a9a',
        text: `Асцендент в ${rising} влияет на первое впечатление и поведение в незнакомой обстановке. Со стороны ты чаще выглядишь как человек, который ${signTrait(rising)}.`,
      },
      {
        pl: `Солнце и Луна`,
        badge: sameElement ? 'Похожий принцип' : 'Разные принципы',
        color: sameElement ? '#9b87c4' : '#e0985a',
        text: sameElement
          ? 'Солнце и Луна относятся к одной стихии. Решение и первая реакция чаще направлены в одну сторону.'
          : 'Солнце и Луна относятся к разным стихиям. То, что кажется правильным, и первая эмоциональная реакция могут не совпадать.',
      },
      {
        pl: 'Общий вывод',
        badge: 'Итог',
        color: '#9a9a9a',
        text: 'Первое впечатление, способ принимать решения и внутренняя реакция у тебя отличаются. Поэтому окружающие не всегда сразу понимают, что ты действительно думаешь.',
      },
    ],
    resume:
      `Солнце в ${sun} описывает решения, Луна в ${moon} — реакцию на напряжение, Асцендент в ${rising} — первое впечатление. ` +
      'Главная разница заметна между тем, как ты выглядишь со стороны, и тем, что происходит до окончательного решения. ' +
      'Подробный разбор должен опираться на дома и реальные аспекты карты; этот запасной текст их не подменяет.',
  };
}

